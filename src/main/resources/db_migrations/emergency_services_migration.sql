-- NEXT GO Emergency Services Module Migration Script
-- Microsoft SQL Server 2019/2022 Schema Definitions

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'emergency_requests')
BEGIN
    CREATE TABLE emergency_requests (
        id BIGINT IDENTITY(1,1) PRIMARY KEY,
        tracking_token VARCHAR(64) NOT NULL UNIQUE,
        idempotency_key VARCHAR(128) NULL,
        requested_services VARCHAR(255) NOT NULL,
        requested_agent_count INT NULL,
        assigned_agents_count INT NOT NULL DEFAULT 0,
        latitude FLOAT NULL,
        longitude FLOAT NULL,
        location_address NVARCHAR(500) NULL,
        location_landmark NVARCHAR(255) NULL,
        contact_name NVARCHAR(100) NULL,
        callback_phone VARCHAR(30) NOT NULL,
        incident_description NVARCHAR(1000) NOT NULL,
        status VARCHAR(50) NOT NULL DEFAULT 'SUBMITTED',
        client_ip VARCHAR(64) NULL,
        created_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
        updated_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
    );

    CREATE INDEX idx_emergency_tracking_token ON emergency_requests(tracking_token);
    CREATE INDEX idx_emergency_status ON emergency_requests(status);
    CREATE INDEX idx_emergency_created_at ON emergency_requests(created_at);
    CREATE INDEX idx_emergency_idempotency ON emergency_requests(idempotency_key);
END;

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'emergency_status_history')
BEGIN
    CREATE TABLE emergency_status_history (
        id BIGINT IDENTITY(1,1) PRIMARY KEY,
        request_id BIGINT NOT NULL,
        status VARCHAR(50) NOT NULL,
        note NVARCHAR(500) NULL,
        changed_by NVARCHAR(100) NOT NULL,
        created_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
        CONSTRAINT fk_emergency_history_request FOREIGN KEY (request_id) REFERENCES emergency_requests(id) ON DELETE CASCADE
    );

    CREATE INDEX idx_emergency_history_request_id ON emergency_status_history(request_id);
END;

-- Additive migration for soft deletion and cryptographic requester management token
IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('emergency_requests') AND name = 'management_token_hash')
BEGIN
    ALTER TABLE emergency_requests ADD management_token_hash VARCHAR(64) NULL;
END;

