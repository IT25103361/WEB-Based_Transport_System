-- Update or drop old check constraints generated by Hibernate to allow DELETED status
DECLARE @chkName NVARCHAR(256);

SELECT @chkName = name FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID('emergency_requests') AND definition NOT LIKE '%DELETED%';
IF @chkName IS NOT NULL
BEGIN
    EXEC('ALTER TABLE emergency_requests DROP CONSTRAINT ' + @chkName);
    ALTER TABLE emergency_requests ADD CONSTRAINT CK_emergency_requests_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'RESPONDERS_ASSIGNED', 'ON_SCENE', 'RESOLVED', 'CANCELLED', 'DELETED'));
END;

SELECT @chkName = name FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID('emergency_status_history') AND definition NOT LIKE '%DELETED%';
IF @chkName IS NOT NULL
BEGIN
    EXEC('ALTER TABLE emergency_status_history DROP CONSTRAINT ' + @chkName);
    ALTER TABLE emergency_status_history ADD CONSTRAINT CK_emergency_status_history_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'RESPONDERS_ASSIGNED', 'ON_SCENE', 'RESOLVED', 'CANCELLED', 'DELETED'));
END;


